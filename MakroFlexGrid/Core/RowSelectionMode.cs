namespace MakroFlexGrid.Core
{
    /// <summary>
    /// Определяет режим выбора строк в CustomDataGrid.
    /// </summary>
    public enum RowSelectionMode
    {
        /// <summary>
        /// Выбор строк запрещён. Клик по строке не изменяет выделение.
        /// </summary>
        None,

        /// <summary>
        /// Можно выбрать только одну строку. Клик по новой строке снимает выделение с предыдущей.
        /// </summary>
        Single,

        /// <summary>
        /// Можно выбрать несколько строк.
        /// - Обычный клик: сбрасывает все выделения и выбирает только текущую строку.
        /// - Ctrl+Click: переключает выбор текущей строки (добавляет/удаляет).
        /// - Shift+Click: выбирает диапазон от последней выбранной до текущей строки.
        /// </summary>
        Multiple
    }
}